import {chromium} from '@playwright/test';
const browser=await chromium.launch({headless:true,channel:"chrome"});
const page=await browser.newPage({viewport:{width:1440,height:1200},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:18485/hackathons/71',{waitUntil:'networkidle'});
await page.evaluate(()=>{document.documentElement.dataset.theme='light';document.dispatchEvent(new Event('site:theme-change'));});
await page.getByRole('button',{name:'Explore in 3D'}).click();
await page.locator('[data-scene]').waitFor({state:'visible'});
await page.locator('[data-scene]').scrollIntoViewIfNeeded();
await page.waitForTimeout(1200);
await page.getByRole('button',{name:'Pause motion',exact:true}).click();
await page.locator('[data-reset]').click();
await page.locator('[data-project-exhibit]').screenshot({path:'outputs/pal-fidelity-review/light.png'});
await page.evaluate(()=>{document.documentElement.dataset.theme='dark';document.dispatchEvent(new Event('site:theme-change'));});
await page.waitForTimeout(300);
await page.locator('[data-project-exhibit]').screenshot({path:'outputs/pal-fidelity-review/dark.png'});
await page.setViewportSize({width:390,height:844});
await page.locator('[data-scene]').scrollIntoViewIfNeeded();await page.waitForTimeout(300);
await page.locator('[data-project-exhibit]').screenshot({path:'outputs/pal-fidelity-review/mobile.png'});
console.log(JSON.stringify({errors,status:await page.locator('[data-status]').textContent()}));
await browser.close();
