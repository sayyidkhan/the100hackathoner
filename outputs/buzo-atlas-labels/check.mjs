import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:18481/hackathons/75/?from=landing');
await page.locator('[data-mode="3d"]').click();
await page.waitForTimeout(2500);
await page.locator('[data-pause]').click();
await page.locator('[data-project-exhibit]').screenshot({path:'outputs/buzo-atlas-labels/desktop.png'});
const label = page.locator('[data-scene] [data-division="originals"]');
const before = await label.getAttribute('style');
await page.locator('canvas').focus();await page.keyboard.press('ArrowRight');await page.waitForTimeout(100);
const after = await label.getAttribute('style');
if (before === after) throw new Error('District label did not follow rotation');
console.log('District label follows rotation.');
await page.locator('[data-reset]').click();
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(500);
await page.locator('[data-project-exhibit]').screenshot({path:'outputs/buzo-atlas-labels/mobile.png'});
console.log(JSON.stringify({errors,status:await page.locator('[data-status]').textContent(),overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)}));
await page.setViewportSize({width:1440,height:1100});
await page.evaluate(()=>{document.documentElement.dataset.theme='dark';document.dispatchEvent(new Event('site:theme-change'));});
await page.waitForTimeout(300);
await page.locator('[data-project-exhibit]').screenshot({path:'outputs/buzo-atlas-labels/dark.png'});
await page.locator('[data-mode="artwork"]').click();
await page.waitForFunction(()=>document.querySelector('[data-art] img').complete && document.querySelector('[data-art] img').naturalWidth > 0);
await page.locator('[data-project-exhibit]').screenshot({path:'outputs/buzo-atlas-labels/artwork.png'});
console.log('Artwork loaded; dark mode rendered.');
await browser.close();
