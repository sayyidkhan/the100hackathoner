import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
const errors=[];page.on('pageerror',e=>errors.push(e.message));
for (const id of [75,76]) {
  await page.goto(`http://127.0.0.1:18481/hackathons/${id}/?from=landing`);
  const toggle=page.locator('[data-toggle-labels]');
  await expect(toggle).toHaveText('Hide labels');
  await expect(page.locator('[data-art] .division-labels')).toBeVisible();
  await toggle.click();
  await expect(page.locator('[data-art] .division-labels')).toBeHidden();
  await expect(page.locator('.division-key')).toBeHidden();
  await page.locator('[data-mode="3d"]').click();
  await expect(page.locator('[data-scene]')).toBeVisible();
  await expect(page.locator('[data-scene] .division-labels')).toBeHidden();
  await toggle.click();
  await expect(page.locator('[data-scene] .division-labels')).toBeVisible();
  await expect(page.locator('.division-key')).toBeVisible();
  await page.locator('[data-mode="artwork"]').click();
  await expect(page.locator('[data-art] .division-labels')).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await toggle.focus();await page.keyboard.press('Enter');
  await expect(toggle).toHaveText('Show labels');
  await expect(page.locator('.division-key')).toBeHidden();
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile overflow');
  await page.locator('[data-project-exhibit]').screenshot({path:`outputs/buzo-atlas-labels/toggle-${id}-mobile.png`});
  await page.setViewportSize({width:1280,height:1000});
}
await page.goto('http://127.0.0.1:18481/hackathons/74/?from=landing');
await expect(page.locator('[data-toggle-labels]')).toHaveCount(0);
if(errors.length)throw new Error(errors.join('\n'));
console.log('Both exhibits: default visible, hide/show, mode switching, keyboard and mobile checks passed. Unlabelled exhibit has no toggle.');
await browser.close();
