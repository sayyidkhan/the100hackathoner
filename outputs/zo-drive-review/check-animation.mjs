import assert from 'node:assert/strict';
import * as T from '../../public/landing/vendor/three.module.js';
import {createArtifact} from '../../public/landing/artifacts/zo-drive.js';
import {chromium} from '@playwright/test';
const model=createArtifact(T), animate=model.userData.animate;
const drawer=model.getObjectByName('file-drawer'), lock=model.getObjectByName('sharing-lock-shackle');
const lights=model.getObjectByName('database-activity').children;
const initial={z:drawer.position.z,y:lock.position.y,light:lights[0].material.emissiveIntensity};
animate(5.5);assert.ok(drawer.position.z<initial.z-.8);assert.ok(lock.position.y>initial.y+.09);assert.notEqual(lights[0].material.emissiveIntensity,initial.light);
assert.ok(lock.rotation.y< -1,'Shackle swings around captive leg');
animate(9.2);assert.ok(Math.abs(lock.rotation.y)<1e-8,'Shackle aligns before lowering');
animate(14);assert.equal(drawer.position.z,initial.z);assert.equal(lock.position.y,initial.y);
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
// Isolate this snapshot from unrelated edits triggering Vite reloads.
await page.routeWebSocket('**',socket=>socket.close());
await page.goto('http://127.0.0.1:18485/hackathons/73/?from=landing');
await page.locator('[data-mode="3d"]').click();
await page.waitForTimeout(1600);
await page.locator('[data-project-exhibit]').screenshot({path:'outputs/zo-drive-review/animated-open.png'});
await page.waitForTimeout(4300);
await page.locator('[data-pause]').click();await page.waitForTimeout(250);
const canvas=page.locator('[data-project-exhibit] canvas');
const paused=await canvas.screenshot();await page.waitForTimeout(1100);assert.ok(paused.equals(await canvas.screenshot()),'Paused canvas remains still');
await page.locator('[data-project-exhibit]').screenshot({path:'outputs/zo-drive-review/animated-closed.png'});
await page.locator('[data-pause]').click();await page.waitForTimeout(600);assert.ok(!paused.equals(await canvas.screenshot()),'Resume changes canvas');
await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(300);
const reduced=await canvas.screenshot();await page.waitForTimeout(900);assert.ok(reduced.equals(await canvas.screenshot()),'Reduced motion remains still');
assert.deepEqual(errors,[]);console.log('PASS: drawer/lock cycle, database activity, pause, resume, reduced motion, no browser errors');
await browser.close();
